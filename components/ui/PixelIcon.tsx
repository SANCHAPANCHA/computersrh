export type IconName = keyof typeof ICONS;

const PATHS: Record<string, string> = Object.fromEntries(
  Object.entries(ICONS).map(([k, rows]) => [
    k,
    rows.flatMap((row, y) => [...row].map((ch, x) => (ch === "#" ? `M${x} ${y}h1v1h-1z` : ""))).join(""),
  ]),
);

export function PixelIcon({ name, size = 16, className, flip, title }: { name: IconName | string; size?: number; className?: string; flip?: boolean; title?: string }) {
  const d = PATHS[name] ?? PATHS.sparkle;
  return (
    <svg
      viewBox="0 0 8 8"
      width={size}
      height={size}
      className={cn("pixelated inline-block flex-none", className)}
      style={flip ? { transform: "scaleX(-1)" } : undefined}
      aria-hidden={title ? undefined : true}
      role={title ? "img" : undefined}
      fill="currentColor"
    >
      {title ? <title>{title}</title> : null}
      <path d={d} />
    </svg>
  );
}
